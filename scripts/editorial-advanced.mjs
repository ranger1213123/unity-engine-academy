// HUMAN_FIELDS

const requested = process.argv.slice(2).map(Number);
for (const original of baseline.modules.filter(m => m.number >= 14 && m.number <= 20 && (!requested.length || requested.includes(m.number)))) {
  const mod = structuredClone(original);
  for (const lesson of mod.lessons) {
    const next = revisions[lesson.id];
    if (!next) throw new Error(`No editorial revision for ${lesson.id}`);
    const {codeExplanation, quizExplanations, quizOptions, ...fields} = next;
    Object.assign(lesson, fields);
    if (codeExplanation) lesson.code.explanation = codeExplanation;
    if (quizExplanations) lesson.quiz.forEach((q,i) => q.explanation = quizExplanations[i]);
    if (quizOptions) lesson.quiz.forEach((q,i) => q.options = quizOptions[i]);
    const count = lesson.theory.flatMap(t=>t.paragraphs).join('').match(/\p{Script=Han}/gu)?.length || 0;
    if (count < 900) throw new Error(`${lesson.id}: only ${count} Chinese characters`);
    if (lesson.teaching.walkthrough.length < 3) throw new Error(`${lesson.id}: missing worked steps`);
  }
  fs.writeFileSync(path.join(root, `content/chapter-${String(mod.number).padStart(2,'0')}.js`), `window.COURSE_MODULES.push(${JSON.stringify(mod,null,2)});\n`);
  console.log(`Rewrote chapter ${mod.number}: ${mod.lessons.map(l=>l.id).join(', ')}`);
}
