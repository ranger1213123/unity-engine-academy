function polish(value) {
  if (typeof value === 'string') return phrases.reduce((result, [from, to]) => result.replaceAll(from, to), value);
  if (Array.isArray(value)) return value.map(polish);
  if (value && typeof value === 'object') return Object.fromEntries(Object.entries(value).map(([key, item]) => [key, polish(item)]));
  return value;
}

export function polishSupplementary(lesson) {
  for (const key of ['goals', 'pitfalls', 'exercise']) lesson[key] = polish(lesson[key]);
  lesson.summary = summaries[lesson.id];
}
