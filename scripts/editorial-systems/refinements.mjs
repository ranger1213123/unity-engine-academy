function mapText(value, pairs) {
  if (typeof value === 'string') return pairs.reduce((text, [from, to]) => text.replaceAll(from, to), value);
  if (Array.isArray(value)) return value.map(x => mapText(x, pairs));
  if (value && typeof value === 'object') return Object.fromEntries(Object.entries(value).map(([key, x]) => [key, mapText(x, pairs)]));
  return value;
}

export function refine(id, revision) {
  if (!revision) return revision;
  const fix = fixes[id];
  const result = mapText(structuredClone(revision), fix?.pairs ?? []);
  if (fix?.extra) result.theory.at(-1)[1] += '\n\n' + fix.extra;
  return result;
}
